package api

import (
	"fmt"
	"slices"
	"strings"
)

// Manifest renders routes as compat/endpoints.yaml.
func Manifest(routes []Route) string {
	sorted := slices.Clone(routes)
	slices.SortFunc(sorted, func(a, b Route) int {
		if order := strings.Compare(strings.ToLower(a.Path), strings.ToLower(b.Path)); order != 0 {
			return order
		}
		return strings.Compare(a.Method, b.Method)
	})
	var out strings.Builder
	out.WriteString("# Generated by jellyscale --print-routes. Do not edit.\n")
	out.WriteString(fmt.Sprintf("baseline: %q\nroutes:\n", Version))
	for _, route := range sorted {
		fmt.Fprintf(&out, "  - {method: %s, path: %q, status: %s, role: %s}\n", route.Method, route.Path, route.Status, route.Role)
	}
	return out.String()
}
